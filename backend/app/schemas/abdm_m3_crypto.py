"""Pydantic schemas for ABDM Milestone 3 (M3) Cryptographic Key Exchange & Health Information Flow.

Conforms to NHA ABDM v0.5 Data Flow & Fidelius Cryptographic Specifications:
- Inbound Health Information Request (/v0.5/health-information/hip/request)
- Asynchronous Acknowledgement Callback (/v0.5/health-information/hip/on-request)
- Key Material (ECDH Curve25519, 32-byte CSPRNG Nonces)
- HKDF-SHA256 Shared Secret and Symmetric Key Derivation
"""

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
import uuid

from pydantic import BaseModel, Field, ConfigDict


class KeyUserInfo(BaseModel):
    """Public key and nonce material generated by a participant (HIU or HIP)."""

    publicKey: str = Field(description="Base64-encoded Curve25519 public key")
    nonce: str = Field(description="Base64-encoded 32-byte cryptographically secure random nonce")

    model_config = ConfigDict(from_attributes=True)


class KeyMaterial(BaseModel):
    """Cryptographic parameters and key material for ECDH key exchange."""

    cryptoAlg: str = Field(default="ECDH", description="Cryptographic algorithm: ECDH")
    curve: str = Field(default="Curve25519", description="Elliptic curve: Curve25519")
    userInfo: KeyUserInfo = Field(description="Public key and random nonce of the party")
    id: Optional[str] = Field(default=None, description="Optional key identifier or reference URI")

    model_config = ConfigDict(from_attributes=True)


class ConsentIdRef(BaseModel):
    """Consent artefact identifier reference."""

    id: str = Field(description="Granted Consent Artefact UUID or identifier")

    model_config = ConfigDict(from_attributes=True)


class HIRequestDateRange(BaseModel):
    """Time window for health records requested."""

    from_date: datetime = Field(alias="from", description="Earliest clinical record date requested")
    to_date: datetime = Field(alias="to", description="Latest clinical record date requested")

    model_config = ConfigDict(from_attributes=True, populate_by_name=True)


class HIRequestDetail(BaseModel):
    """Detailed health information request payload received from Gateway/HIU."""

    consent: ConsentIdRef = Field(description="Consent Artefact reference granting data access")
    dateRange: HIRequestDateRange = Field(description="Time window for records requested")
    dataPushUrl: str = Field(description="Secure destination URL where HIP will push encrypted FHIR bundles")
    keyMaterial: KeyMaterial = Field(description="HIU's ephemeral Curve25519 public key and nonce")

    model_config = ConfigDict(from_attributes=True, populate_by_name=True)


class HIRequestPayload(BaseModel):
    """ABDM Gateway Inbound Health Information Request: POST /v0.5/health-information/hip/request."""

    requestId: uuid.UUID = Field(
        default_factory=uuid.uuid4,
        description="Unique request identifier generated by ABDM Gateway",
    )
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp of the request",
    )
    transactionId: uuid.UUID = Field(
        default_factory=uuid.uuid4,
        description="Unique transaction identifier spanning the entire health data exchange flow",
    )
    hiRequest: HIRequestDetail = Field(description="Health information request details and key material")

    model_config = ConfigDict(from_attributes=True)


class HIOnRequestAcknowledgement(BaseModel):
    """Acknowledgement status sent back to ABDM Gateway."""

    transactionId: uuid.UUID = Field(description="Transaction identifier from initial hiRequest")
    status: str = Field(default="ACKNOWLEDGED", description="Processing status: ACKNOWLEDGED | ERROR")

    model_config = ConfigDict(from_attributes=True)


class GatewayHIError(BaseModel):
    """Standardized ABDM Gateway error structure."""

    code: int = Field(description="NHA error code (e.g. 1400, 1401, 1441)")
    message: str = Field(description="Human-readable description of error")

    model_config = ConfigDict(from_attributes=True)


class GatewayRespRef(BaseModel):
    """Correlation reference to inbound Gateway requestId."""

    requestId: uuid.UUID = Field(description="Correlation UUID of original request")

    model_config = ConfigDict(from_attributes=True)


class HIOnRequestCallback(BaseModel):
    """ABDM Gateway Acknowledgement Callback: POST /v0.5/health-information/hip/on-request."""

    requestId: uuid.UUID = Field(
        default_factory=uuid.uuid4,
        description="Unique identifier for the acknowledgement callback",
    )
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp of callback dispatch",
    )
    hiRequest: Optional[HIOnRequestAcknowledgement] = Field(
        default=None,
        description="Acknowledgement payload when successful",
    )
    error: Optional[GatewayHIError] = Field(
        default=None,
        description="Error details if consent validation or key processing failed",
    )
    resp: GatewayRespRef = Field(description="Correlation reference to the original requestId")

    model_config = ConfigDict(from_attributes=True)


class KeyGenerationResponse(BaseModel):
    """Ephemeral key pair and nonce response for testing or local initiation."""

    publicKey: str = Field(description="Base64-encoded Curve25519 public key")
    privateKey: str = Field(description="Base64-encoded Curve25519 private key (kept secret)")
    nonce: str = Field(description="Base64-encoded 32-byte CSPRNG nonce")
    cryptoAlg: str = Field(default="ECDH")
    curve: str = Field(default="Curve25519")

    model_config = ConfigDict(from_attributes=True)


class KeyExchangeComputeRequest(BaseModel):
    """Direct key exchange computation request for verification."""

    localPrivateKey: str = Field(description="Base64-encoded local Curve25519 private key")
    localNonce: str = Field(description="Base64-encoded local 32-byte nonce")
    peerPublicKey: str = Field(description="Base64-encoded peer Curve25519 public key")
    peerNonce: str = Field(description="Base64-encoded peer 32-byte nonce")

    model_config = ConfigDict(from_attributes=True)


class KeyExchangeComputeResponse(BaseModel):
    """Cryptographic computation output verifying shared secret and derived keys."""

    sharedSecretHex: str = Field(description="Hex-encoded 32-byte ECDH shared secret")
    derivedKeyHex: str = Field(description="Hex-encoded 32-byte HKDF-SHA256 symmetric encryption key")
    saltHex: str = Field(description="Hex-encoded 20-byte HKDF salt derived from XOR of nonces")
    ivHex: str = Field(description="Hex-encoded 12-byte AES-GCM IV derived from XOR of nonces")
    status: str = Field(default="SUCCESS")

    model_config = ConfigDict(from_attributes=True)


class CryptoSessionDetail(BaseModel):
    """Active cryptographic session stored in HIP cache for subsequent encrypted data transfer."""

    transactionId: str = Field(description="Data flow transaction ID")
    consentId: str = Field(description="Authorized consent artefact ID")
    dataPushUrl: str = Field(description="Destination URL for encrypted push")
    hipPublicKey: str = Field(description="Base64-encoded HIP public key")
    hipNonce: str = Field(description="Base64-encoded HIP nonce")
    hiuPublicKey: str = Field(description="Base64-encoded HIU public key")
    hiuNonce: str = Field(description="Base64-encoded HIU nonce")
    derivedKeyHex: str = Field(description="Hex-encoded 32-byte derived symmetric key")
    saltHex: str = Field(description="Hex-encoded 20-byte salt")
    ivHex: str = Field(description="Hex-encoded 12-byte IV")
    dateRangeFrom: datetime = Field(description="Earliest authorized date")
    dateRangeTo: datetime = Field(description="Latest authorized date")
    createdAt: datetime = Field(description="UTC timestamp when session was established")
    expiresAt: datetime = Field(description="UTC timestamp when session expires")

    model_config = ConfigDict(from_attributes=True)

